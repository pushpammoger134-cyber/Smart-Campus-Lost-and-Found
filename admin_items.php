<?php
session_start();
require_once __DIR__ . '/db.php';

if (empty($_SESSION['user_id'])) {
    header('Location: login.php');
    exit;
}

$adminId = (int) $_SESSION['user_id'];

// Only administrators may access this page.
$statement = $pdo->prepare('SELECT role FROM users WHERE id = :id');
$statement->execute(['id' => $adminId]);

if ($statement->fetchColumn() !== 'admin') {
    http_response_code(403);
    exit('Access denied. This page is for administrators only.');
}

if (empty($_SESSION['csrf_token'])) {
    $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
}

function escape(string $value): string
{
    return htmlspecialchars($value, ENT_QUOTES, 'UTF-8');
}

$error = '';
$success = $_SESSION['moderation_success'] ?? '';
unset($_SESSION['moderation_success']);

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $token = is_string($_POST['csrf_token'] ?? null)
        ? $_POST['csrf_token'] : '';

    $reason = is_string($_POST['reason'] ?? null)
        ? trim($_POST['reason']) : '';

    $rawId = is_string($_POST['item_id'] ?? null)
        ? $_POST['item_id'] : '';

    $itemId = filter_var(
        $rawId,
        FILTER_VALIDATE_INT,
        ['options' => ['min_range' => 1]]
    );

    if (!hash_equals($_SESSION['csrf_token'], $token)) {
        $error = 'Your form expired. Refresh and try again.';
    } elseif ($itemId === false) {
        $error = 'Invalid report.';
    } elseif (($_POST['confirm'] ?? '') !== 'yes') {
        $error = 'Tick the confirmation checkbox before removing a report.';
    } elseif (mb_strlen($reason) < 5 || mb_strlen($reason) > 250) {
        $error = 'Enter a removal reason between 5 and 250 characters.';
    } else {
        $removedImage = null;

        try {
            $pdo->beginTransaction();

            // Lock the report while it is being removed.
            $statement = $pdo->prepare(
                'SELECT id, user_id, image_path, status
                 FROM items WHERE id = :id FOR UPDATE'
            );
            $statement->execute(['id' => $itemId]);
            $item = $statement->fetch();

            if (!$item) {
                throw new DomainException('This report has already been removed.');
            }

            // Preserve completed returns and items awaiting handover.
            if (in_array($item['status'], ['under_review', 'returned'], true)) {
                throw new DomainException(
                    'Reports awaiting handover or already returned cannot be removed here.'
                );
            }

            $statement = $pdo->prepare(
                'SELECT id, claimant_id, status
                 FROM claims
                 WHERE item_id = :item_id
                 FOR UPDATE'
            );
            $statement->execute(['item_id' => $itemId]);
            $claims = $statement->fetchAll();

            foreach ($claims as $claim) {
                if ($claim['status'] === 'approved') {
                    throw new DomainException(
                        'A report with an approved ownership claim cannot be removed here.'
                    );
                }
            }

            // Notify the reporter and any claimants.
            $recipientIds = [(int) $item['user_id']];

            foreach ($claims as $claim) {
                $recipientIds[] = (int) $claim['claimant_id'];
            }

            $recipientIds = array_unique($recipientIds);

            $notification = $pdo->prepare(
                'INSERT INTO notifications (user_id, message)
                 VALUES (:user_id, :message)'
            );

            $message =
                "Report #$itemId and any associated claims were removed "
                . "by an administrator. Reason: $reason";

            foreach ($recipientIds as $recipientId) {
                $notification->execute([
                    'user_id' => $recipientId,
                    'message' => $message
                ]);
            }

            // Delete dependent claims first.
            // Existing notification references become NULL through
            // the foreign-key rules in our database schema.
            $statement = $pdo->prepare(
                'DELETE FROM claims WHERE item_id = :item_id'
            );
            $statement->execute(['item_id' => $itemId]);

            $statement = $pdo->prepare(
                'DELETE FROM items WHERE id = :id'
            );
            $statement->execute(['id' => $itemId]);

            $removedImage = $item['image_path'];

            $pdo->commit();

            // Remove only a filename generated by our upload code.
            if (
                is_string($removedImage) &&
                preg_match(
                    '~^uploads/[a-f0-9]{32}\.(jpg|png)$~D',
                    $removedImage
                ) === 1
            ) {
                $imageFile = __DIR__ . '/' . $removedImage;

                if (is_file($imageFile) && !@unlink($imageFile)) {
                    error_log('Could not delete removed report photo: ' . $imageFile);
                }
            }

            $_SESSION['moderation_success'] =
                "Report #$itemId was removed. Affected users were notified.";

            header('Location: admin_items.php');
            exit;
        } catch (Throwable $exception) {
            if ($pdo->inTransaction()) {
                $pdo->rollBack();
            }

            if ($exception instanceof DomainException) {
                $error = $exception->getMessage();
            } else {
                error_log($exception->getMessage());
                $error = 'Could not remove the report. Please try again.';
            }
        }
    }
}

$items = [];
$search = is_string($_GET['search'] ?? null)
    ? mb_substr(trim($_GET['search']), 0, 150) : '';

try {
    $sql =
        'SELECT i.id, i.title, i.description, i.report_type,
                i.status, i.location, i.created_at, u.full_name
         FROM items i
         JOIN users u ON u.id = i.user_id';

    $params = [];

    if ($search !== '') {
        $pattern = '%' . strtr($search, [
            '!' => '!!',
            '%' => '!%',
            '_' => '!_'
        ]) . '%';

        $sql .= " WHERE i.title LIKE :search ESCAPE '!'";
        $params['search'] = $pattern;
    }

    $sql .= ' ORDER BY i.created_at DESC, i.id DESC LIMIT 100';

    $statement = $pdo->prepare($sql);
    $statement->execute($params);
    $items = $statement->fetchAll();
} catch (PDOException $exception) {
    error_log($exception->getMessage());
    $error = 'Could not load reports. Please refresh.';
}
